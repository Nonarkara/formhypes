/* ── the oracle ──────────────────────────────────────────────────────────────
   The model was made faster in one pass: the skin integration, the daylight
   quadrature, the plan rebuild and the core test were rewritten to stop
   allocating. A faster model that quietly rounds differently is a worse model,
   so the code it replaced is kept here, verbatim, as the oracle.

   Every assertion below compares the studio's current code against this file
   or against the recorded run. If a future change makes them disagree, this
   test is the witness. */

const intersectsRef=(a,b,c,d)=>{
  const cross=(p,q,r)=>(q[0]-p[0])*(r[1]-p[1])-(q[1]-p[1])*(r[0]-p[0]);
  return cross(a,b,c)*cross(a,b,d)<0&&cross(c,d,a)*cross(c,d,b)<0;
};
function coreBoundaryHitRef(p,core){
  const c=core/2,r=[[-c,-c],[c,-c],[c,c],[-c,-c]];
  return p.some((v,i)=>r.some((w,j)=>intersectsRef(v,p[(i+1)%p.length],w,r[(j+1)%4])));
}
function coreHitRef(p,core){
  const c=core/2;
  return coreBoundaryHitRef(p,core)||p.some(([x,y])=>Math.abs(x)<c&&Math.abs(y)<c)
    ||[[-c,-c],[c,-c],[c,c],[-c,-c]].some(v=>pointInPolygon(p,v));
}
function cornerZonesRef(p,s){
  let out=[];
  for(let i=0;i<p.length;i++){
    let v=p[i],prev=p[(i+p.length-1)%p.length],next=p[(i+1)%p.length];
    let u=[prev[0]-v[0],prev[1]-v[1]],w=[next[0]-v[0],next[1]-v[1]];
    let lu=Math.hypot(...u),lw=Math.hypot(...w);
    if(lu<2*s.frontage+.01||lw<2*s.frontage+.01)continue;
    u=u.map(x=>x/lu);w=w.map(x=>x/lw);
    const cross=u[0]*w[1]-u[1]*w[0];
    const angle=Math.acos(Math.max(-1,Math.min(1,u[0]*w[0]+u[1]*w[1])));
    if(cross>=0||angle>145*Math.PI/180)continue;
    const l=s.frontage;
    const z=[v,[v[0]+u[0]*l,v[1]+u[1]*l],[v[0]+(u[0]+w[0])*l,v[1]+(u[1]+w[1])*l],[v[0]+w[0]*l,v[1]+w[1]*l]];
    if(coreHitRef(z,s.core))continue;
    const centroid=z.reduce((a,v)=>[a[0]+v[0]/4,a[1]+v[1]/4],[0,0]);
    if(!pointInPolygon(p,z[2])||!pointInPolygon(p,centroid))continue;
    out.push(z);
  }
  return out;
}
function daylitFractionRef(p,reach,N=28){
  let xs=[Infinity,-Infinity],ys=[Infinity,-Infinity];
  for(const [x,y] of p){xs[0]=Math.min(xs[0],x);xs[1]=Math.max(xs[1],x);ys[0]=Math.min(ys[0],y);ys[1]=Math.max(ys[1],y)}
  const w=xs[1]-xs[0],h=ys[1]-ys[0];
  if(w<1e-12||h<1e-12)return 0;
  let inside=0,lit=0;
  for(let i=0;i<N;i++)for(let j=0;j<N;j++){
    const v=[xs[0]+w*(i+.5)/N,ys[0]+h*(j+.5)/N];
    if(!pointInPolygon(p,v))continue;
    inside++;
    if(distToBoundary(p,v)<=reach)lit++;
  }
  return inside?lit/inside:0;
}

/* ── the states the comparison covers ─────────────────────────────────────── */

const fams=Object.keys(M.families);
function states(){
  const out=[];
  for(const family of fams){
    for(const [taper,twist,floors,span,aspect] of [
      [1,0,48,48,1],[0.8,30,32,52,0.8],[0.7,90,20,44,1.3],[1.2,180,60,56,1],
      [1,45,12,20,1],[0.95,15,70,36,1.1],[1,0,8,16,1],[0.6,120,40,60,0.9]]){
      out.push({...M.defaults,family,taper,twist,floors,span,aspect});
    }
  }
  // The awkward cases: a plan barely bigger than its core, a frontage wider
  // than the plan, a core that touches the plan's edge.
  for(const span of [8,10,12,14,16,18,20,26,30]){
    out.push({...M.defaults,family:'box',span,core:14,frontage:6});
    out.push({...M.defaults,family:'cross',span,core:14,frontage:6});
    out.push({...M.defaults,family:'octagon',span,core:14,frontage:3});
    out.push({...M.defaults,family:'petal',span,core:18,frontage:9});
  }
  return out;
}

/* ── the corner test ─────────────────────────────────────────────────────── */

test('the corner-zone test agrees with the array version it replaced', () => {
  let checked=0;
  for(const s of states()){
    for(const t of [0,0.25,0.5,0.75,1]){
      const p=M.profile(s,t);
      const got=M.cornerZones(p,s);
      const want=cornerZonesRef(p,s);
      assert.equal(got.length,want.length,
        `zone count differs for ${s.family} span ${s.span} core ${s.core} t ${t}`);
      for(let i=0;i<got.length;i++){
        for(let k=0;k<4;k++){
          assert.equal(got[i][k][0],want[i][k][0]);
          assert.equal(got[i][k][1],want[i][k][1]);
        }
      }
      checked++;
    }
  }
  assert.ok(checked>300,`only ${checked} plans were compared`);
});

test('a core the zone touches is still found', () => {
  // The fast path is allowed to skip the core test only when the answer is
  // false. This is the case where the answer is true.
  for(const span of [12,14,16,20,24]){
    for(const core of [10,14,18]){
      const s={...M.defaults,family:'box',span,core,frontage:6};
      const p=M.profile(s,0);
      assert.equal(M.cornerZones(p,s).length,cornerZonesRef(p,s).length,
        `span ${span} core ${core}`);
    }
  }
});

/* ── the daylight quadrature ─────────────────────────────────────────────── */

test('the daylight quadrature agrees with the distance it replaced', () => {
  let checked=0;
  for(const s of states()){
    const p=M.profile(s,0);
    for(const reach of [2.4,3.2,4.5,6.0,9.0]){
      const got=daylitFraction(p,reach);
      const want=daylitFractionRef(p,reach);
      assert.equal(got,want,
        `daylit fraction differs for ${s.family} span ${s.span} reach ${reach}: ${got} vs ${want}`);
      checked++;
    }
  }
  assert.ok(checked>100,`only ${checked} quadratures were compared`);
});

