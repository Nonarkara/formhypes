test('the model still answers exactly as the recorded run', () => {
  let checked=0;
  for(const [key,want] of GOLDEN){
    const [family,taper,twist,floors,span,aspect,program,crown,garden,material,skin,system]=key.split('|');
    const s={...M.defaults,family,taper:+taper,twist:+twist,floors:+floors,span:+span,
      aspect:+aspect,program,crown,garden,material,skin,system};
    const m=M.evaluate(s);
    METRICS.forEach((name,i)=>{
      const got=m[name];
      if(typeof want[i]!=='number')return;
      assert.ok(Math.abs(got-want[i])<=Math.max(1e-9,Math.abs(want[i])*1e-12),
        `${key} ${name}: got ${got}, recorded ${want[i]}`);
    });
    checked++;
  }
  assert.equal(checked,GOLDEN.length);
  assert.ok(checked>=50,`only ${checked} recorded states were replayed`);
});

test('every family still produces a feasible, finite, conserving tower', () => {
  for(const family of fams){
    const m=M.evaluate({...M.defaults,family});
    assert.ok(Number.isFinite(m.gross)&&m.gross>0,family);
    assert.ok(Number.isFinite(m.rentable)&&m.rentable>=0,family);
    assert.ok(m.rentable<=m.gross+1e-6,`${family}: rentable exceeds gross`);
    assert.ok(Math.abs(m.core+m.common+m.rentable-m.gross)<1e-6,
      `${family}: the areas do not add up`);
  }
});

test('the model is fast enough to search with', () => {
  // A search is a few hundred evaluations. If this regresses, the studio's
  // comparison stops being an instrument and becomes a wait. The bound is
  // generous on purpose: it should fail only if the work grows by an order.
  const s=M.defaults;
  for(let i=0;i<10;i++)M.evaluate(s);
  const t=process.hrtime.bigint();
  for(let i=0;i<30;i++)M.evaluate(s);
  const ms=Number(process.hrtime.bigint()-t)/1e6/30;
  assert.ok(ms<60,`an evaluation takes ${ms.toFixed(1)} ms`);
});
